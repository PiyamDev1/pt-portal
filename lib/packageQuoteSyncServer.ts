export async function markPackageQuoteSyncFailed(
  supabase: SupabaseClient,
  packageId: string,
  error: unknown,
) {
  const { data } = await supabase
    .from('travel_packages')
    .select('metadata')
    .eq('id', packageId)
    .maybeSingle()
  const metadata = metadataOf(data?.metadata)
  await supabase
    .from('travel_packages')
    .update({
      metadata: {
        ...metadata,
        quoteSync: {
          status: 'failed',
          failedAt: new Date().toISOString(),
          message: error instanceof Error ? error.message : 'Package reconciliation failed',
        },
      },
    })
    .eq('id', packageId)
}

type ExistingReservation = TravelPackageReservation & {
  itemCount: number
}

type DesiredReservation = PackageQuoteReservationDraft & {
  quoteId: string | null
  groupMemberId: string | null
  familyLabel: string | null
  currency: string
  depositRequired: boolean
  depositAmount: number
}

type DesiredPaymentRequest = {
  quoteId: string
  groupMemberId: string | null
  familyLabel: string | null
  source: 'final_quote_deposit_request' | 'final_quote_payment_breakdown'
  paymentType: 'deposit' | 'payment'
  paymentMethod: 'cash' | 'bank_transfer' | 'card'
  amount: number
  currency: string
  notes: string
  metadata: Record<string, unknown>
}

